// Pure helpers for the Prisma migration workflow (scripts/db-migrations.mjs).
// No I/O here so the rules can be unit-tested (tests/migration-workflow.test.ts).
import { createHash } from "node:crypto";

export const MIGRATION_NAME = /^(0_baseline|\d{14}_[a-z0-9_]+)$/;

export function sha256(content) {
  return createHash("sha256").update(content).digest("hex");
}

/** Schema fingerprint that ignores comments, blank lines and formatting. */
export function schemaFingerprint(schemaText) {
  const lines = [];
  for (const raw of schemaText.replace(/\r\n?/g, "\n").split("\n")) {
    let out = "";
    let inString = false;
    for (let i = 0; i < raw.length; i++) {
      const ch = raw[i];
      if (ch === '"' && raw[i - 1] !== "\\") inString = !inString;
      if (!inString && ch === "/" && raw[i + 1] === "/") break;
      out += ch;
    }
    const line = out.replace(/\s+/g, " ").trim();
    if (line) lines.push(line);
  }
  return sha256(lines.join("\n"));
}

/** Folder-level rules: names, duplicates, empty files, provider lock. */
export function checkMigrationLayout({ migrations, lockText }) {
  const errors = [];
  if (!lockText) errors.push("prisma/migrations/migration_lock.toml is missing.");
  else if (!/provider\s*=\s*"mysql"/.test(lockText)) errors.push('migration_lock.toml must declare provider = "mysql".');
  const byTimestamp = new Map();
  for (const { name, sql } of migrations) {
    if (!MIGRATION_NAME.test(name)) errors.push(`Migration folder "${name}" must be named <14-digit timestamp>_<lowercase_name>.`);
    if (sql === null || sql === undefined) errors.push(`Migration "${name}" has no migration.sql.`);
    else if (!sql.trim()) errors.push(`Migration "${name}" has an empty migration.sql.`);
    const stamp = name.split("_")[0];
    if (name !== "0_baseline") byTimestamp.set(stamp, [...(byTimestamp.get(stamp) || []), name]);
  }
  for (const [stamp, names] of byTimestamp)
    if (names.length > 1) errors.push(`Duplicate migration timestamp ${stamp}: ${names.join(", ")}. Keep one, or regenerate the newer one.`);
  return errors;
}

export function buildManifest(schemaText, migrations) {
  return {
    note: "Generated by npm run db:migrate. Do not edit by hand; on a merge conflict, keep either side and run npm run db:migrate.",
    schema: schemaFingerprint(schemaText),
    migrations: Object.fromEntries([...migrations].sort((a, b) => a.name.localeCompare(b.name)).map((m) => [m.name, sha256(m.sql)])),
  };
}

/** Compares the committed manifest with the current schema and migration files. */
export function checkManifest(manifest, schemaText, migrations) {
  if (!manifest) return ["prisma/migration-manifest.json is missing. Run npm run db:migrate."];
  const errors = [];
  if (manifest.schema !== schemaFingerprint(schemaText))
    errors.push("prisma/schema.prisma changed, but no matching migration was generated and recorded. Run npm run db:migrate, then commit the schema, the new migration folder and prisma/migration-manifest.json together.");
  const recorded = manifest.migrations || {};
  const present = new Map(migrations.map((m) => [m.name, sha256(m.sql)]));
  for (const name of Object.keys(recorded))
    if (!present.has(name)) errors.push(`Migration "${name}" is recorded but missing from prisma/migrations. Commit or pull it.`);
  for (const [name, hash] of present) {
    if (!(name in recorded)) errors.push(`Migration "${name}" is not recorded in prisma/migration-manifest.json. Run npm run db:migrate.`);
    else if (recorded[name] !== hash) errors.push(`Migration "${name}" was modified after it was recorded. Never edit a migration that may already be applied; add a new migration instead.`);
  }
  return errors;
}

export function isEmptyMigration(sql) {
  return !stripComments(sql).trim();
}

function stripComments(sql) {
  // Prisma prefixes risky statements with a /* Warnings: ... */ block.
  return sql.replace(/\r\n?/g, "\n").replace(/\/\*[\s\S]*?\*\//g, "").split("\n").filter((l) => !l.trim().startsWith("--")).join("\n");
}

function statementsOf(sql) {
  return stripComments(sql).split(/;\s*(?:\n|$)/).map((s) => s.replace(/\s+/g, " ").trim()).filter(Boolean);
}

/** Splits an ALTER TABLE body on top-level commas. */
function clausesOf(body) {
  const out = [];
  let depth = 0, cur = "", quote = "";
  for (const ch of body) {
    if (quote) { cur += ch; if (ch === quote) quote = ""; continue; }
    if (ch === "'" || ch === "`") { quote = ch; cur += ch; continue; }
    if (ch === "(") depth++;
    if (ch === ")") depth--;
    if (ch === "," && depth === 0) { out.push(cur.trim()); cur = ""; continue; }
    cur += ch;
  }
  if (cur.trim()) out.push(cur.trim());
  return out;
}

/**
 * Classifies every statement of a generated migration. Anything that can lose data,
 * fail on existing rows, or needs a data transformation is returned as a risk and
 * requires explicit approval before it is applied.
 */
export function analyzeMigrationSql(sql) {
  const statements = statementsOf(sql);
  const newTables = new Set(statements.map((s) => s.match(/^CREATE TABLE `([^`]+)`/i)?.[1]).filter(Boolean));
  const risks = [];
  const risk = (level, statement, reason) => risks.push({ level, statement: statement.slice(0, 200), reason });
  for (const s of statements) {
    let m;
    if (/^CREATE TABLE /i.test(s) || /^CREATE INDEX /i.test(s) || /^DROP INDEX /i.test(s)) continue;
    if ((m = s.match(/^CREATE UNIQUE INDEX `[^`]+` ON `([^`]+)`/i))) {
      if (!newTables.has(m[1])) risk("risky", s, "New unique index on an existing table fails if duplicate values already exist.");
      continue;
    }
    if (/^DROP TABLE /i.test(s)) { risk("destructive", s, "Drops a table and all of its rows."); continue; }
    if (/^RENAME TABLE /i.test(s)) { risk("risky", s, "Renames a table; running code still uses the old name."); continue; }
    if ((m = s.match(/^ALTER TABLE `([^`]+)` (.*)$/i))) {
      const table = m[1];
      const isNew = newTables.has(table);
      for (const c of clausesOf(m[2])) {
        if (/^DROP COLUMN /i.test(c)) risk("destructive", `ALTER TABLE \`${table}\` ${c}`, "Drops a column and its data. If this is a rename, change the SQL to RENAME COLUMN before approving.");
        else if (/^DROP PRIMARY KEY/i.test(c)) risk("destructive", `ALTER TABLE \`${table}\` ${c}`, "Changes the primary key.");
        else if (/^(MODIFY|CHANGE) /i.test(c)) risk("risky", `ALTER TABLE \`${table}\` ${c}`, "Changes a column type, length, nullability, default or enum values; can fail or truncate existing data.");
        else if (/^RENAME /i.test(c)) risk("risky", `ALTER TABLE \`${table}\` ${c}`, "Renames a column or table; running code still uses the old name.");
        else if (/^ADD (COLUMN )?`/i.test(c)) {
          if (!isNew && /NOT NULL/i.test(c) && !/DEFAULT /i.test(c) && !/AUTO_INCREMENT/i.test(c))
            risk("risky", `ALTER TABLE \`${table}\` ${c}`, "Required column without a default fails on a table that already has rows. Add a default, make it optional first, or backfill in a staged migration.");
        } else if (/^ADD CONSTRAINT `[^`]+` FOREIGN KEY/i.test(c)) {
          if (!isNew) risk("risky", `ALTER TABLE \`${table}\` ${c}`, "New foreign key on an existing table fails if existing rows violate it.");
        } else if (/^ADD (UNIQUE|CONSTRAINT `[^`]+` UNIQUE)/i.test(c)) {
          if (!isNew) risk("risky", `ALTER TABLE \`${table}\` ${c}`, "New unique constraint fails if duplicate values already exist.");
        } else if (/^ADD PRIMARY KEY/i.test(c)) {
          if (!isNew) risk("destructive", `ALTER TABLE \`${table}\` ${c}`, "Changes the primary key.");
        } else if (/^(DROP FOREIGN KEY|DROP INDEX|ADD (INDEX|KEY|FULLTEXT)|ALTER COLUMN .* SET DEFAULT|ALTER COLUMN .* DROP DEFAULT)/i.test(c)) {
          // No row data is lost.
        } else risk("risky", `ALTER TABLE \`${table}\` ${c}`, "Unrecognised change; review it.");
      }
      continue;
    }
    risk("risky", s, "Data or unrecognised statement; review it.");
  }
  return risks;
}

/** Descriptive migration name derived from the generated SQL. */
export function suggestMigrationName(sql) {
  const ss = statementsOf(sql);
  const created = ss.map((s) => s.match(/^CREATE TABLE `([^`]+)`/i)?.[1]).filter(Boolean);
  let name = "";
  if (created.length) name = `add_${created[0]}_table${created.length > 1 ? "s" : ""}`;
  else {
    for (const s of ss) {
      const m = s.match(/^ALTER TABLE `([^`]+)` (.*)$/i);
      if (!m) continue;
      const c = clausesOf(m[2])[0] || "";
      const col = c.match(/`([^`]+)`/)?.[1];
      if (/^ADD (COLUMN )?`/i.test(c)) name = `add_${m[1]}_${col}`;
      else if (/^DROP COLUMN/i.test(c)) name = `remove_${m[1]}_${col}`;
      else if (/^(MODIFY|CHANGE)/i.test(c)) name = `change_${m[1]}_${col}`;
      else if (/FOREIGN KEY/i.test(c)) name = `update_${m[1]}_relations`;
      if (name) break;
    }
    if (!name && ss.some((s) => /^CREATE (UNIQUE )?INDEX/i.test(s))) name = `add_${ss.find((s) => /^CREATE (UNIQUE )?INDEX/i.test(s)).match(/ON `([^`]+)`/i)?.[1] || "schema"}_index`;
    if (!name && ss.some((s) => /^DROP TABLE/i.test(s))) name = `remove_${ss.find((s) => /^DROP TABLE/i.test(s)).match(/`([^`]+)`/)?.[1]}_table`;
  }
  return (name || "schema_update").toLowerCase().replace(/[^a-z0-9_]+/g, "_").replace(/_+/g, "_").replace(/^_|_$/g, "").slice(0, 60) || "schema_update";
}

/**
 * Development safety guard: automatic migration generation only runs against a local database.
 * Extra hosts can be allowed with DEV_DATABASE_HOSTS (comma-separated).
 */
export function assertDevelopmentDatabase(databaseUrl, env = {}) {
  if (!databaseUrl) throw new Error("DATABASE_URL is not set. Add your local development database to .env.local (see docs/DATABASE_MIGRATIONS.md).");
  if (env.NODE_ENV === "production") throw new Error("NODE_ENV is production. Automatic migration generation never runs in production; deployments use npm run build:deploy.");
  let url;
  try { url = new URL(databaseUrl); } catch { throw new Error("DATABASE_URL is not a valid URL."); }
  if (url.protocol !== "mysql:") throw new Error(`DATABASE_URL must use mysql:// (found ${url.protocol}).`);
  const host = url.hostname.replace(/^\[|\]$/g, "");
  const allowed = new Set(["localhost", "127.0.0.1", "::1", ...String(env.DEV_DATABASE_HOSTS || "").split(",").map((h) => h.trim()).filter(Boolean)]);
  if (!allowed.has(host)) throw new Error(`Refusing to generate or apply development migrations on host "${host}". Only local databases are allowed; this protects production.`);
  const database = decodeURIComponent(url.pathname.slice(1));
  if (!database) throw new Error("DATABASE_URL has no database name.");
  if (/^u\d+_/.test(database)) throw new Error(`Database "${database}" looks like the Hostinger production database. Use a local development database.`);
  return { host, database };
}
